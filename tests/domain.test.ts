test('popularidade respeita cardápio e avaliação de sobras tem denominador por item',()=>{
  const c=createTicket(initialState(false),'42',at);
  let s=saveMenu(c.state,date,['arroz','lasanha']);
  s=saveBuffet(s,c.plate.id,{...composition,foodIds:['arroz','lasanha'],noMeat:true},at);
  s=saveWaste(s,c.plate.id,{at:later,note:'',outcomes:{arroz:'nao_avaliado',lasanha:'grande'}});
  const next='2026-11-26T15:00:00.000Z';
  const c2=createTicket(s,'43',next);
  s=saveMenu(c2.state,day(next),['arroz']);
  s=saveBuffet(s,c2.plate.id,{...composition,foodIds:['arroz'],noMeat:true},next);
  s=saveWaste(s,c2.plate.id,{at:next,note:'',outcomes:{arroz:'sem_sobra'}});
  s=saveDiscard(s,{at:next,foodId:'lasanha',level:'media',note:''});
  const a=analytics(s,range(2,day(next)));
  const lasanha=a.foods.find(f=>f.id==='lasanha')!;
  const arroz=a.foods.find(f=>f.id==='arroz')!;
  assert.deepEqual([lasanha.selected,lasanha.eligible,lasanha.popularity,lasanha.assessed,lasanha.rate],[1,1,100,1,100]);
  assert.deepEqual([arroz.eligible,arroz.assessed,arroz.rate],[2,1,0]);
  assert.equal(a.coverage,100);
  assert.equal(a.wasteRate,50);
  assert.equal(a.discards.length,1);
  const corrected = saveDiscard(s,{at:next,foodId:'lasanha',level:'grande',note:'Correção'},s.discards[0].id);
  assert.equal(corrected.discards.length,1);
  assert.equal(corrected.discards[0].level,'grande');
  assert.equal(analytics(corrected,range(2,day(next))).wasteRate,50);
  assert.equal(analytics(s,{...range(2,day(next)),ticket:'0042'}).discards.length,0);
});
test('filtros, insights e dashboard refletem a jornada e respectivas correções',()=>{
  const c=createTicket(initialState(false),'0042',at);
  const filter={...range(1,date),ticket:'0042',fromHour:'12',toHour:'12',meat:'picanha',food:'lasanha',category:'quentes'};
  const a0=analytics(c.state,filter);
  let s=saveGrill(c.state,c.plate.id,portions,at);
  s=saveBuffet(s,c.plate.id,composition,at);
  s=saveWaste(s,c.plate.id,{at:later,note:'',outcomes:{...noWaste(plateFoods(s.plates[0])),lasanha:'grande'}});
  const a1=analytics(s,filter);
  assert.equal(a0.plates.length,0);
  assert.equal(a1.plates.length,1);
  assert.equal(a1.revenue,52.14);
  assert.equal(a1.cost,13.88);
  assert.equal(a1.withWaste,1);
  assert.equal(a1.cuts[0].id,'picanha');
  assert.equal(a1.hours[0].label,'12h');
  assert.match(insights(a1,analytics(s,priorRange(filter)),s)[0].text,/custo dos cortes/);
  assert.equal(analytics(s,{...filter,fromHour:'13',toHour:'13'}).plates.length,0);
  const correction=saveWaste(s,c.plate.id,{at:later,note:'',outcomes:noWaste(plateFoods(s.plates[0]))});
  assert.equal(analytics(correction,filter).withWaste,0);
});
test('IndexedDB restaura dados e rejeita gravações concorrentes com revisão obsoleta',async()=>{
  const {IDBFactory}=await import('fake-indexeddb');
  const factory=new IDBFactory();
  const seed=()=>initialState(true);
  const r=new BrowserRepository(factory,seed);
  const first=await r.load();
  const other=new BrowserRepository(factory,seed);
  const stale=await other.load();
  const {state:next}=createTicket(first,'0042',at);
  const saved=await r.commit(next,first);
  assert.equal(saved.revision,1);
  await assert.rejects(other.commit(stale,stale),Conflict);
  assert.equal((await other.load()).tickets[0].number,'0042');
  await other.commit(seed(),saved);
  assert.equal((await r.load()).tickets.length,0);
});
