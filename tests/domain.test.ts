const later='2026-11-25T15:45:00.000Z';
const portions=[{foodId:'picanha',size:'media' as const,count:2},{foodId:'frango',size:'media' as const,count:1}];
const composition={weight:580,composition:'completa' as const,foodIds:['arroz','feijao','salada','lasanha'],noMeat:false};

test('calcula carnes, acompanhamentos, receita, resultado e CMV do exemplo',()=>{
  const meats: Meat[]=[{foodId:'corte',size:'media',count:2,grams:125,costKg:50,recordedAt:at}];
  const f=estimate(600,meats,{saleKg:89.9,sideKg:12},at);
  assert.equal(meatCost(meats),12.5);
  assert.equal(f.revenue,53.94);
  assert.equal(f.sideG,350);
  assert.equal(f.sideCost,4.2);
  assert.equal(f.cost,16.7);
  assert.equal(f.result,37.24);
  assert.equal(f.cmv?.toFixed(2),'30.96');
  assert.equal(f.meatShare.toFixed(2),'41.67');
});
test('trata divisão por zero e rejeita pesos e custos inconsistentes',()=>{
  assert.equal(ratio(0,0),null);
  assert.equal(estimate(500,[],{saleKg:0,sideKg:12},at).cmv,null);
  assert.throws(()=>estimate(Infinity,[],{saleKg:89.9,sideKg:12},at),/Confira/);
  assert.throws(()=>estimate(0,[],{saleKg:89.9,sideKg:12},at),/Confira/);
  assert.throws(()=>estimate(500,[],{saleKg:89.9,sideKg:-1},at),/Confira/);
  const c=createTicket(initialState(false),'42',at);
  const s=saveGrill(c.state,c.plate.id,portions,at);
  assert.throws(()=>saveBuffet(s,c.plate.id,{...composition,weight:150},at),/supera o peso/);
  assert.equal(s.plates[0].weight,null);
});
test('comandas com vários pratos, prevenção de duplicidade e sessões reutilizadas',()=>{
  const c=createTicket(initialState(false),'42',at);
  assert.equal(c.ticket.number,'0042');
  assert.throws(()=>createTicket(c.state,'00042',at),/sessão aberta/);
  const p2=addPlate(c.state,c.ticket.id,at);
  assert.equal(p2.plate.sequence,2);
  assert.notEqual(p2.plate.id,c.plate.id);
  assert.throws(()=>saveGrill(p2.state,p2.plate.id,[portions[0],portions[0]],at),/Agrupe/);
  const closed=closeTicket(p2.state,c.ticket.id,later);
  assert.throws(()=>addPlate(closed,c.ticket.id,later),/aberta/);
  assert.notEqual(createTicket(closed,'0042',later).ticket.id,c.ticket.id);
});
test('preserva preços unitários e histórico após correção da pesagem e alteração do catálogo',()=>{
  const c=createTicket(initialState(false),'42',at);
  const grill=saveGrill(c.state,c.plate.id,portions,at);
  const first=saveBuffet(grill,c.plate.id,composition,at);
  const p=first.plates[0];
  assert.equal(p.finance?.cost,13.88);
  const cut=first.foods.find(f=>f.id==='picanha')!;
  const s=saveFood(saveSettings(first,{...first.settings,saleKg:100,sideKg:20}),{...cut,costKg:80});
  const corrected=saveBuffet(s,c.plate.id,{...composition,weight:600},later);
  assert.equal(corrected.plates[0].finance?.revenue,53.94);
  assert.equal(corrected.plates[0].finance?.sideCost,4.8);
  assert.equal(corrected.plates[0].meats[0].costKg,65);
  assert.equal(corrected.plates[0].financeHistory.length,2);
  assert.equal(corrected.plates[0].financeHistory[0].finance.cost,13.88);
  assert.equal(saveBuffet(corrected,c.plate.id,{...composition,weight:600},later).plates[0].financeHistory.length,2);
  assert.equal(saveGrill(corrected,c.plate.id,[portions[1]],later).plates[0].financeHistory.at(-2)?.finance.meatInputs?.[0].costKg,65);
});
